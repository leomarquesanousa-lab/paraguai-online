<?php
/** Selected media or original local artwork. @package MarquesanoStore */
defined( 'ABSPATH' ) || exit;
$id = marquesano_store_setting( 'hero_image' );
$image = $id ? wp_get_attachment_image( $id, 'full', false, array( 'loading' => 'eager', 'fetchpriority' => 'high', 'sizes' => '(max-width: 760px) 100vw, 65vw' ) ) : '';
?>
<div class="hero-media <?php echo $image ? 'is-photograph' : 'is-artwork'; ?>">
	<?php if ( $image ) {
		echo $image; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- generated by WordPress.
	} else { ?>
	<img src="<?php echo esc_url( get_template_directory_uri() . '/assets/art/' . marquesano_store_setting( 'preset' ) . '.svg' ); ?>" width="1200" height="1000" alt="" fetchpriority="high">
	<?php } ?>
</div>
